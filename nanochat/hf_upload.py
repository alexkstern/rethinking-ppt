"""HuggingFace push for training checkpoints.

`push_checkpoint` creates a model repo and uploads the per-step artifacts
`checkpoint.save_checkpoint` wrote, plus an autogenerated `README.md` model
card. Rank-0 only: callers must guard with `if ctx.rank == 0`.

`huggingface_hub` is imported lazily so the package stays an extra rather than
a hard dependency.

The repo name is the canonical run identity (`{cfg.run_name}_{ctx.run_timestamp}`,
also the local checkpoint dir basename and the W&B run name), so one handle
traces a checkpoint across local / W&B / HF.
"""

from __future__ import annotations

import json
import logging
import os
import time
from pathlib import Path
from typing import Callable

logger = logging.getLogger(__name__)

_MAX_RETRIES = 5
_RETRY_DELAY_BASE_S = 10  # linear backoff: 10s, 20s, 30s, 40s -> ~100s of cover
_RETRYABLE_SUBSTRINGS = (
    "timeout", "timed out", "connection", "reset by peer",
    "broken pipe", "network", "temporary failure",
    # Hub-side 5xx: the server failed, not the request, so a retry is worth it.
    # 4xx (auth, quota, bad repo) still fails fast.
    "500 ", "502 ", "503 ", "504 ", "service unavailable", "bad gateway",
    "internal error",
)


def _is_retryable(exc: BaseException) -> bool:
    """Allowlist transient network errors; everything else fails immediately."""
    msg = str(exc).lower()
    return any(s in msg for s in _RETRYABLE_SUBSTRINGS)


def _retry_on_timeout(func: Callable, *args, **kwargs):
    """Call `func` with up to `_MAX_RETRIES` retries on transient errors,
    re-raising the last one when they are exhausted."""
    last: BaseException | None = None
    for attempt in range(_MAX_RETRIES):
        try:
            return func(*args, **kwargs)
        except Exception as e:
            if not _is_retryable(e):
                raise
            last = e
            if attempt < _MAX_RETRIES - 1:
                delay = _RETRY_DELAY_BASE_S * (attempt + 1)
                logger.warning(f"upload attempt {attempt + 1} failed ({e}); retrying in {delay}s")
                time.sleep(delay)
            else:
                logger.error(f"all {_MAX_RETRIES} upload attempts failed")
    assert last is not None
    raise last


# Public alias: the same retry policy applies to HF downloads.
retry_on_timeout = _retry_on_timeout


def push_checkpoint(
    *,
    ckpt_dir: str | Path,
    step: int,
    repo_name: str,
    hf_token: str | None = None,
    public: bool = True,
    repo_type: str = "model",
    include_optim: bool = True,
    wandb_run_url: str | None = None,
) -> str:
    """Create the repo if needed, upload the step's artifacts, return the repo URL.

    `repo_name` is fully qualified (e.g. `"alexkstern/myrun_2026-..."`).
    `hf_token` falls back to the `HF_TOKEN` env var. `include_optim=False` skips
    the large rank-specific optimizer shards, which only a resume needs.
    """
    try:
        from huggingface_hub import HfApi, create_repo
    except ImportError as e:
        raise ImportError(
            "huggingface_hub is required for push_checkpoint; install with "
            "`uv pip install huggingface-hub` (it's usually transitively pulled in)."
        ) from e

    token = hf_token if hf_token is not None else os.getenv("HF_TOKEN")
    if not token:
        raise ValueError(
            "no HF token supplied — pass `hf_token=...` or set the HF_TOKEN env var "
            "(create one at https://huggingface.co/settings/tokens with write access)"
        )

    ckpt_dir = Path(ckpt_dir)
    files_to_upload: list[tuple[Path, str]] = []  # (local_path, repo_relpath)

    for stem in ("model", "meta", "config", "rng"):
        ext = "pt" if stem in ("model", "rng") else "json"
        local = ckpt_dir / f"{stem}_{step:06d}.{ext}"
        if not local.exists():
            if stem == "rng":
                continue  # rng is optional
            raise FileNotFoundError(f"expected checkpoint artifact missing: {local}")
        files_to_upload.append((local, local.name))

    if include_optim:
        for shard in sorted(ckpt_dir.glob(f"optim_{step:06d}_rank*.pt")):
            files_to_upload.append((shard, shard.name))
        if not any(p.name.startswith(f"optim_{step:06d}") for p, _ in files_to_upload):
            logger.warning(
                f"include_optim=True but no optim_{step:06d}_rank*.pt shards found in {ckpt_dir}"
            )

    # Built from the on-disk config + meta, so the card reflects what the run
    # actually wrote rather than a second in-memory source of truth.
    readme = _render_model_card(
        ckpt_dir=ckpt_dir, step=step, repo_name=repo_name, wandb_run_url=wandb_run_url,
    )
    readme_path = ckpt_dir / "README.md"
    readme_path.write_text(readme, encoding="utf-8")
    files_to_upload.append((readme_path, "README.md"))

    api = HfApi(token=token)
    _retry_on_timeout(
        create_repo,
        repo_id=repo_name,
        repo_type=repo_type,
        token=token,
        private=not public,
        exist_ok=True,
    )

    for local_path, repo_path in files_to_upload:
        _retry_on_timeout(
            api.upload_file,
            path_or_fileobj=str(local_path),
            path_in_repo=repo_path,
            repo_id=repo_name,
            repo_type=repo_type,
            token=token,
        )
        logger.info(f"uploaded {local_path.name} -> {repo_name}/{repo_path}")

    url = f"https://huggingface.co/{repo_name}"
    logger.info(f"push_checkpoint done: {url} (step={step}, files={len(files_to_upload)})")
    return url


def _render_model_card(
    *, ckpt_dir: Path, step: int, repo_name: str, wandb_run_url: str | None,
) -> str:
    """Build a Markdown model card from the on-disk meta + config snapshots."""
    meta = json.loads((ckpt_dir / f"meta_{step:06d}.json").read_text())
    config = json.loads((ckpt_dir / f"config_{step:06d}.json").read_text())

    lines: list[str] = [
        "---",
        "library_name: nanochat",
        "license: apache-2.0",
        "tags:",
        "- nanochat",
    ]
    for tag in (config.get("wandb", {}) or {}).get("tags") or []:
        lines.append(f"- {tag}")
    lines.append("---")
    lines.append("")
    lines.append(f"# {repo_name.split('/')[-1]}")
    lines.append("")
    lines.append(
        f"Trained with [nanochat](https://github.com/karpathy/nanochat). "
        f"Checkpoint at step **{step:,}**."
    )
    lines.append("")

    if wandb_run_url:
        lines.append(f"**W&B run:** {wandb_run_url}")
        lines.append("")

    # Keys match `CheckpointMeta`'s on-disk fields.
    lines.append("## Outcome")
    lines.append("")
    lines.append("| metric | value |")
    lines.append("| --- | --- |")
    for key in ("step", "smooth_train_loss", "min_objective",
                "flops_used", "flops_per_token", "total_training_time"):
        if key in meta and meta[key] is not None:
            lines.append(f"| `{key}` | {meta[key]} |")
    lines.append("")

    # The whole snapshot, so the run's hyperparameters stay recoverable.
    lines.append("## Training config")
    lines.append("")
    lines.append("```json")
    lines.append(json.dumps(config, indent=2, default=str))
    lines.append("```")
    lines.append("")

    lines.append("## Files")
    lines.append("")
    lines.append(f"- `model_{step:06d}.pt` — model weights (`state_dict`).")
    lines.append(f"- `meta_{step:06d}.json` — training metadata.")
    lines.append(f"- `config_{step:06d}.json` — run config snapshot.")
    lines.append(f"- `rng_{step:06d}.pt` — RNG state (when present).")
    lines.append("")

    return "\n".join(lines)
